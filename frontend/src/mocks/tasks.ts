const DAY_MS = 86_400_000;
const at = (date: string, time = '18:00') => `${date}T${time}:00-06:00`;
const shift = (ts: string, days: number) =>
  new Date(new Date(ts).getTime() + days * DAY_MS).toISOString();

const position: Record<string, number> = {};
const nextPosition = (lane: string) => (position[lane] = (position[lane] ?? -1) + 1);

interface OpenSeed {
  code: number;
  title: string;
  areaId: Id;
  status: Exclude<TaskStatus, 'done'>;
  priority: Priority;
  dueAt: string;
  createdAt?: string;
  startDate?: string | null;
  description?: string;
  targetBuildId?: Id;
}

interface DoneSeed {
  code: number;
  title: string;
  areaId: Id;
  doneState: DoneState;
  priority: Priority;
  completedAt: string;
  integratedBuildId: Id;
  changeNote?: string;
  createdAt?: string;
  dueAt?: string;
}

function open(s: OpenSeed): Task {
  const createdAt = s.createdAt ?? at('2026-09-01', '10:00');
  return {
    id: `t-${s.code}`,
    code: `QL-${String(s.code).padStart(3, '0')}`,
    title: s.title,
    description: s.description ?? '',
    areaId: s.areaId,
    assigneeId: OWNER[s.areaId],
    status: s.status,
    doneState: null,
    changeNote: null,
    priority: s.priority,
    startDate: s.startDate === undefined ? '2026-09-15' : s.startDate,
    dueAt: s.dueAt,
    completedAt: null,
    targetBuildId: s.targetBuildId ?? null,
    integratedBuildId: null,
    position: nextPosition(s.status),
    createdBy: 'u-lm',
    createdAt,
    updatedAt: createdAt,
  };
}

function done(s: DoneSeed): Task {
  const lane = s.doneState === 'active' ? 'done_active' : 'done_changed';
  return {
    id: `t-${s.code}`,
    code: `QL-${String(s.code).padStart(3, '0')}`,
    title: s.title,
    description: '',
    areaId: s.areaId,
    assigneeId: OWNER[s.areaId],
    status: 'done',
    doneState: s.doneState,
    changeNote: s.changeNote ?? null,
    priority: s.priority,
    startDate: shift(s.completedAt, -7).slice(0, 10),
    dueAt: s.dueAt ?? at(s.completedAt.slice(0, 10)),
    completedAt: s.completedAt,
    targetBuildId: null,
    integratedBuildId: s.integratedBuildId,
    position: nextPosition(lane),
    createdBy: 'u-lm',
    createdAt: s.createdAt ?? shift(s.completedAt, -14),
    updatedAt: s.completedAt,
  };
}

